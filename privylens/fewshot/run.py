"""The few-shot experiment: unseen companies, K = 1 / 5 / 10 examples, several methods, same scoring as the rest of the project.

Run:  python -m privylens.fewshot.run [--steps 1500] [--seeds 5]
Out:  reports/fewshot.md, reports/figures/fewshot_f1_vs_k.png, checkpoints/fewshot.pt (the model the app loads)
Numbers per cell = mean +- std over 15 unseen companies x seeds (each seed draws a different set of K examples).
  F1      exact-span F1 for the new category
  missed  share of real IDs not fully hidden (privacy risk)
  false   share of harmless characters hidden by mistake (usability cost)
"""
import argparse
import os
import random
import statistics as st
import torch
from privylens.evaluation.metrics import evaluate
from privylens.fewshot import baselines as B
from privylens.fewshot.data import CUES_TEST, CUES_TRAIN, candidates, make_company, rows
from privylens.fewshot.model import detector, train_proto

KS = (1, 5, 10)


def split(pool_rows):
    """Support pool -> positives and negatives as (text,start,end), the form detectors take."""
    pos, neg = [], []
    for r in pool_rows:
        gold = {(s["start"], s["end"]) for s in r["spans"]}
        for a, b in candidates(r["text"]):
            (pos if (a, b) in gold else neg).append((r["text"], a, b))
    return pos, neg


def main(steps=1500, seeds=5, out="reports/fewshot.md"):
    rng = random.Random(0)
    train = [make_company(rng, CUES_TRAIN) for _ in range(40)]
    test = [make_company(rng, CUES_TEST) for _ in range(15)]
    models = {v: train_proto(train, v, steps) for v in ("shape", "context", "both")}
    base, decoys = B.pretrain_clf(train, steps // 2)
    os.makedirs("checkpoints", exist_ok=True)
    torch.save(models["both"].state_dict(), "checkpoints/fewshot.pt")
    tag = B.tagger() if os.path.exists("checkpoints/tagger.pt") else None

    res = {}                                                   # (method, K) -> [metrics per company x seed]
    for ci, c in enumerate(test):
        ev = rows(c, 60, random.Random(1000 + ci))
        pos, neg = split(rows(c, 60, random.Random(2000 + ci)))
        for K in KS:
            for s in range(seeds):
                r = random.Random(100 * s + ci)
                sup, nsup = r.sample(pos, K), r.sample(neg, 5)
                dets = {"regex (induced)": B.induce_regex(sup),
                        "fine-tune": B.finetune(base, decoys, sup, r),
                        "few-shot: shape only": detector(models["shape"], sup),
                        "few-shot: context only": detector(models["context"], sup),
                        "few-shot: shape + context": detector(models["both"], sup),
                        "few-shot: + calibrated cut-off": detector(models["both"], sup, calibrate=True),
                        "few-shot: + 5 'not this' examples": detector(models["both"], sup, nsup),
                        "few-shot: examples without sentences": detector(models["both"], sup, bare=True)}
                if tag and s == 0: dets["existing tagger (no examples)"] = tag     # does not depend on K or the draw
                for name, d in dets.items():
                    e = evaluate(d, ev)
                    res.setdefault((name, K), []).append((e["micro"]["F1"], e["leaked_span"], e["over_redact"]))
        print(f"company {ci + 1}/{len(test)} done", flush=True)

    ms = lambda v: f"{st.mean(v):.3f} +- {st.pstdev(v):.3f}"
    lines = ["# Few-shot detection of unseen ID formats (auto-generated by `python -m privylens.fewshot.run`)\n",
             f"{len(train)} train companies, {len(test)} unseen test companies, {seeds} example draws each. mean +- std. Lower is better for missed / false.\n"]
    for K in KS:
        lines += [f"\n## K = {K} example(s)\n", "| method | F1 | missed IDs | false redaction |", "|---|---|---|---|"]
        for name in dict.fromkeys(n for n, _ in res):
            if (name, K) in res: v = res[(name, K)]; lines.append(f"| {name} | {ms([x[0] for x in v])} | {ms([x[1] for x in v])} | {ms([x[2] for x in v])} |")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))

    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    for name in dict.fromkeys(n for n, _ in res):
        if all((name, K) in res for K in KS):
            plt.plot(KS, [st.mean(x[0] for x in res[(name, K)]) for K in KS], marker="o", label=name)
    plt.xscale("log"); plt.xticks(KS, KS); plt.xlabel("examples given (K)"); plt.ylabel("F1 on unseen companies"); plt.legend(fontsize=7)
    os.makedirs("reports/figures", exist_ok=True); plt.savefig("reports/figures/fewshot_f1_vs_k.png", dpi=150, bbox_inches="tight")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--steps", type=int, default=1500); ap.add_argument("--seeds", type=int, default=5)
    a = ap.parse_args(); main(a.steps, a.seeds)
